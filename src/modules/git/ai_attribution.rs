    fn wildcard_matching() {
        assert!(wildcard("made with *", "Made with Foo"));
        assert!(wildcard("a?c", "abc"));
        assert!(!wildcard("a?c", "abbc"));
        assert!(wildcard("*[x](*)", "see [x](url)"));
    }

    #[test]
    fn validates_options() {
        let mut t = toml::Table::new();
        t.insert("policy".into(), "remove".into());
        t.insert("comment_char".into(), "##".into());
        t.insert(
            "extra_agent_emails".into(),
            toml::Value::Array(vec!["nobody".into()]),
        );
        t.insert(
            "extra_signature_patterns".into(),
            toml::Value::Array(vec!["*".into()]),
        );
        t.insert("bogus".into(), true.into());
        assert_eq!(AiAttribution.validate_options(&t).len(), 5);

        let mut ok = toml::Table::new();
        ok.insert("policy".into(), "warn-only".into());
        ok.insert(
            "extra_agent_names".into(),
            toml::Value::Array(vec!["Acme Bot".into()]),
        );
        assert!(AiAttribution.validate_options(&ok).is_empty());
    }

