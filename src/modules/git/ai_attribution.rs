    fn modes_and_policies() {
        let msg = "s\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n";
        let warn = run(msg, &RuleSettings::with_mode(RuleMode::Warn));
        assert_eq!(warn.findings.len(), 1);
        assert!(warn.fixes.is_empty() && !warn.findings[0].fixable);
        assert_eq!(warn.findings[0].line, Some(3));

        let block = run(msg, &RuleSettings::with_mode(RuleMode::Block));
        assert_eq!(
            block.findings[0].severity,
            crate::core::model::Severity::Error
        );

        let mut s = RuleSettings::with_mode(RuleMode::Fix);
        s.options.insert("policy".into(), "warn-only".into());
        let r = run(msg, &s);
        assert_eq!(r.findings.len(), 1);
        assert!(r.fixes.is_empty());

        s.options.insert("policy".into(), "keep".into());
        assert_eq!(run(msg, &s), RuleResult::empty());
    }

